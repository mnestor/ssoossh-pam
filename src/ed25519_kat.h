/* Known answers for the Ed25519 self-test both crypto backends run before
 * claiming to support ssh-ed25519.
 *
 * Only one backend is compiled into any given module, so this is one copy
 * of the vectors rather than two that could drift. They are runtime
 * self-test data, not test-suite data: tests/unit/ed25519_test.c carries
 * its own, larger table and asserts the acceptance profile; this header
 * is the smallest set that tells a backend whether the primitive it found
 * is the right one.
 *
 *   SSOOSSH_ED25519_KAT      RFC 8032 section 7.1 TEST 3      must verify
 *   the same with one signature byte flipped                   must not
 *   SSOOSSH_ED25519_BIG_S    ed25519-speccheck case 6, S >= L  must not
 *
 * The third is what catches a primitive that verifies but has quietly
 * loosened: S below the group order is the malleability check RFC 8032
 * requires and every serious verifier makes.
 */
